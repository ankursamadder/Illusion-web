/**
 * Returns cities for a given state
 */
export const getCitiesForState = (stateName) => {
  if (!stateName) return []
  return STATE_CITIES[stateName] || []
}

/**
 * Returns default pincode for given state & city from our static dataset
 */
export const getDefaultPincodeForCity = (stateName, cityName) => {
  if (!stateName || !cityName) return ''
  const cities = STATE_CITIES[stateName] || []
  const found = cities.find(
    (c) => c.city.toLowerCase() === cityName.toLowerCase()
  )
  return found?.pincode || ''
}

/**
 * Normalizes state name to match our standard list
 */
export const normalizeStateName = (rawState) => {
  if (!rawState) return ''
  const clean = String(rawState).trim().toLowerCase()

  if (clean.includes('delhi')) return 'Delhi'
  if (clean.includes('orissa')) return 'Odisha'
  if (clean.includes('pondicherry') || clean.includes('puducherry')) return 'Puducherry'
  if (clean.includes('daman') || clean.includes('diu') || clean.includes('dadra'))
    return 'Dadra and Nagar Haveli and Daman and Diu'
  if (clean.includes('andaman') || clean.includes('nicobar'))
    return 'Andaman and Nicobar Islands'
  if (clean.includes('jammu') || clean.includes('kashmir')) return 'Jammu and Kashmir'
  if (clean.includes('ladakh')) return 'Ladakh'

  const direct = INDIAN_STATES.find(
    (s) => s.toLowerCase() === clean || clean.includes(s.toLowerCase())
  )
  return direct || ''
}

/**
 * Look up location by 6-digit PIN code using:
 * 1. Static dataset search
 * 2. Real-time API via zippopotam.us (CORS enabled) with timeout
 */
export const fetchLocationByPincode = async (pincode) => {
  const cleanPin = String(pincode || '').replace(/\D/g, '')
  if (cleanPin.length !== 6) return null

  // 1. Fast lookup from local dataset
  for (const [state, cities] of Object.entries(STATE_CITIES)) {
    const match = cities.find((c) => c.pincode === cleanPin)
    if (match) {
      return {
        state,
        city: match.city,
        pincode: cleanPin,
        source: 'local',
      }
    }
  }

  // 2. Online lookup with CORS support and 4s timeout
  try {
    const controller = new AbortController()
    const timer = setTimeout(() => controller.abort(), 4000)

    const response = await fetch(`https://api.zippopotam.us/in/${cleanPin}`, {
      signal: controller.signal,
    })
    clearTimeout(timer)

    if (response.ok) {
      const data = await response.json()
      const place = data?.places?.[0]
      if (place) {
        const detectedState = normalizeStateName(place.state)
        // Clean place name (e.g. remove " G P O", " H O", " S.O.")
        const rawPlace = String(place['place name'] || '')
          .replace(/\b(g\s*p\s*o|h\s*o|s\s*o|b\s*o)\b/gi, '')
          .trim()

        return {
          state: detectedState || place.state,
          city: rawPlace,
          pincode: cleanPin,
          source: 'api',
        }
      }
    }
  } catch {
    // Graceful fallback if offline or request aborted
  }

  return null
}
